set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="$ROOT_DIR/scripts/deploy-user-service.sh"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

status=0

pass() {
	printf 'ok    %s\n' "$1"
}

fail() {
	printf 'FAIL  %s\n' "$1" >&2
	status=1
}

write_fake_kandev() {
	local path="$1"
	cat >"$path" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
{
	printf 'argv:'
	printf ' %q' "$0" "$@"
	printf '\n'
} >>"${KANDEV_ARGV_LOG:?}"
EOF
	chmod +x "$path"
}

make_complete_bundle() {
	local bundle_dir="$1"
	mkdir -p "$bundle_dir/bin"
	write_fake_kandev "$bundle_dir/bin/kandev"
	touch \
		"$bundle_dir/bin/agentctl" \
		"$bundle_dir/bin/agentctl-linux-amd64" \
		"$bundle_dir/bin/agentctl-linux-arm64" \
		"$bundle_dir/bin/agentctl-darwin-arm64" \
		"$bundle_dir/bin/agentctl-darwin-amd64"
	chmod +x "$bundle_dir/bin/"*
}

write_managed_unit() {
	local unit_path="$1" home_dir="$2" port="${3:-}" db_path="${4:-}"
	mkdir -p "$(dirname "$unit_path")"
	{
		printf '%s\n' '# managed by kandev — regenerated by `kandev service install`'
		printf '%s\n' '[Service]'
		printf 'Environment=KANDEV_HOME_DIR=%s\n' "$home_dir"
		if [ -n "$port" ]; then
			printf 'Environment=KANDEV_SERVER_PORT=%s\n' "$port"
		fi
		if [ -n "$db_path" ]; then
			printf 'Environment=KANDEV_DATABASE_PATH=%s\n' "$db_path"
		fi
	} >"$unit_path"
}

new_home() {
	local dir
	dir="$(mktemp -d "$TMP_DIR/home.XXXXXX")"
	mkdir -p "$dir/.config/systemd/user"
	printf '%s\n' "$dir"
}

# Fake service managers keep service state out of the host: the idle gate reads
# active state through systemctl (Linux) or launchctl (Darwin).
FAKE_BIN="$TMP_DIR/fakebin"
mkdir -p "$FAKE_BIN"
cat >"$FAKE_BIN/systemctl" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
for arg in "$@"; do
	if [ "$arg" = "is-active" ]; then
		if [ "${KANDEV_FAKE_SERVICE_ACTIVE:-inactive}" = "active" ]; then
			exit 0
		fi
		exit 3
	fi
done
exit 0
EOF
cat >"$FAKE_BIN/launchctl" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
if [ "${1:-}" = "print" ] && [ "${KANDEV_FAKE_SERVICE_ACTIVE:-inactive}" = "active" ]; then
	exit 0
fi
exit 3
EOF
cat >"$FAKE_BIN/uname" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "${KANDEV_FAKE_UNAME:-Linux}"
EOF
chmod +x "$FAKE_BIN/"*
KANDEV_FAKE_SERVICE_ACTIVE=inactive
KANDEV_FAKE_UNAME=Linux

write_kandev_db() {
	local db_path="$1"
	mkdir -p "$(dirname "$db_path")"
	python3 - "$db_path" <<'PY'
import sqlite3, sys
conn = sqlite3.connect(sys.argv[1])
conn.executescript("""
CREATE TABLE tasks (id TEXT PRIMARY KEY, title TEXT NOT NULL, archived_at TIMESTAMP);
CREATE TABLE task_sessions (id TEXT PRIMARY KEY, task_id TEXT NOT NULL, state TEXT NOT NULL);
CREATE TABLE agent_delivery_submissions (id TEXT PRIMARY KEY, session_id TEXT NOT NULL, state TEXT NOT NULL);
CREATE TABLE session_recovery_blocks (id TEXT PRIMARY KEY, session_id TEXT NOT NULL, state TEXT NOT NULL);
""")
conn.commit()
conn.close()
PY
}

seed_db() {
	local db_path="$1" sql="$2"
	python3 - "$db_path" "$sql" <<'PY'
import sqlite3, sys
conn = sqlite3.connect(sys.argv[1])
conn.executescript(sys.argv[2])
conn.commit()
conn.close()
PY
}

run_deploy() {
	local home="$1"
	shift
	env -u HOME_DIR -u PORT -u NO_BOOT_START \
		HOME="$home" \
		PATH="$FAKE_BIN:$PATH" \
		KANDEV_ARGV_LOG="$home/argv.log" \
		KANDEV_FAKE_SERVICE_ACTIVE="$KANDEV_FAKE_SERVICE_ACTIVE" \
		KANDEV_FAKE_UNAME="$KANDEV_FAKE_UNAME" \
		XDG_CONFIG_HOME="$home/.config" \
		"$SCRIPT" "$@"
}

