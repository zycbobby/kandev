	if [ -x "$published" ]; then
		pass "default home publishes to \$HOME/.kandev/runtime"
	else
		fail "default home publishes to \$HOME/.kandev/runtime"
	fi
	if grep -q 'service install' "$home/argv.log" && ! grep -q -- '--system' "$home/argv.log"; then
		pass "install is user-domain (no --system)"
	else
		fail "install is user-domain (no --system): $(cat "$home/argv.log")"
	fi
