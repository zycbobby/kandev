# --- idle gate refuses a busy live database before publishing ---
prepare_busy_home() {
	local seed_sql="$1"
	BUSY_HOME="$(new_home)"
	BUSY_CHECKOUT="$(mktemp -d "$TMP_DIR/checkout.XXXXXX")"
	BUSY_LIVE_HOME="$BUSY_HOME/.kandev"
	mkdir -p "$BUSY_LIVE_HOME/runtime/bin"
	printf 'OLD\n' >"$BUSY_LIVE_HOME/runtime/bin/kandev"
	chmod +x "$BUSY_LIVE_HOME/runtime/bin/kandev"
	BUSY_BUNDLE="$BUSY_HOME/staging"
	make_complete_bundle "$BUSY_BUNDLE"
	write_kandev_db "$BUSY_LIVE_HOME/data/kandev.db"
	seed_db "$BUSY_LIVE_HOME/data/kandev.db" "$seed_sql"
	: >"$BUSY_HOME/argv.log"
}

assert_busy_refusal() {
	local label="$1" task_id="$2" title="$3" reason="$4"
	if [ -s "$BUSY_HOME/argv.log" ]; then
		fail "$label: service install/restart ran before the gate"
	else
		pass "$label: no install/restart before refusal"
	fi
	if grep -q OLD "$BUSY_LIVE_HOME/runtime/bin/kandev"; then
		pass "$label: live runtime is untouched"
	else
		fail "$label: live runtime was replaced"
	fi
	if grep -qF "$task_id" "$BUSY_HOME/err" && grep -qF "$title" "$BUSY_HOME/err"; then
		pass "$label: refusal names task id and title"
	else
		fail "$label: refusal names task id and title: $(cat "$BUSY_HOME/err")"
	fi
	if grep -qF "$reason" "$BUSY_HOME/err" && grep -qF -- '--force' "$BUSY_HOME/err"; then
		pass "$label: refusal names the reason and suggests --force"
	else
		fail "$label: refusal names the reason and suggests --force: $(cat "$BUSY_HOME/err")"
	fi
}

run_busy_case() {
	local label="$1" seed_sql="$2" task_id="$3" title="$4" reason="$5"
	prepare_busy_home "$seed_sql"
	if run_deploy "$BUSY_HOME" --bundle-dir "$BUSY_BUNDLE" --checkout "$BUSY_CHECKOUT" >"$BUSY_HOME/out" 2>"$BUSY_HOME/err"; then
		fail "$label: deploy should be refused"
		return
	fi
	assert_busy_refusal "$label" "$task_id" "$title" "$reason"
}

